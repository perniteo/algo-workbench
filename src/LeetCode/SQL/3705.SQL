-- 3705. Find Golden Hour Customers

WITH ORDER_SUMMARY AS (
    SELECT CUSTOMER_ID,
    COUNT(*) AS ORDER_COUNT,
    SUM(CASE WHEN TIME(ORDER_TIMESTAMP) BETWEEN '11:00:00' AND '14:00:00' THEN 1
    WHEN TIME(ORDER_TIMESTAMP) BETWEEN '18:00:00' AND '21:00:00' THEN 1 ELSE 0 END) AS PEAK_COUNT,
    ROUND(AVG(ORDER_RATING), 2) AS AVG_RATING,
    SUM(CASE WHEN ORDER_RATING IS NOT NULL THEN 1 ELSE 0 END) AS RATE_COUNT
    FROM RESTAURANT_ORDERS
    GROUP BY CUSTOMER_ID
)

SELECT CUSTOMER_ID, ORDER_COUNT AS TOTAL_ORDERS, ROUND(PEAK_COUNT / ORDER_COUNT * 100) AS PEAK_HOUR_PERCENTAGE, AVG_RATING AS AVERAGE_RATING
FROM ORDER_SUMMARY
WHERE PEAK_COUNT / ORDER_COUNT >= 0.6
AND ORDER_COUNT >= 3
AND AVG_RATING >= 4.0
AND RATE_COUNT / ORDER_COUNT >= 0.5
ORDER BY AVERAGE_RATING DESC, CUSTOMER_ID DESC