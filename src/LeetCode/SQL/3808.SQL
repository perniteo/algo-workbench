-- 3808. Find Emotionally Consistent Users

WITH USER_REACTION AS (SELECT USER_ID, COUNT(*) AS COUNT_ALL
FROM REACTIONS
GROUP BY USER_ID
HAVING COUNT(*) >= 5),

USER_RATIO AS (SELECT R.USER_ID, R.REACTION, ROUND(COUNT(*) / COUNT_ALL, 2) AS REACTION_RATIO
FROM REACTIONS R
JOIN USER_REACTION U ON R.USER_ID = U.USER_ID
GROUP BY R.USER_ID, R.REACTION
)

SELECT USER_ID, REACTION AS DOMINANT_REACTION, REACTION_RATIO FROM USER_RATIO
WHERE REACTION_RATIO >= 0.6
ORDER BY REACTION_RATIO DESC, USER_ID