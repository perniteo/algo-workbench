-- 3554. Find Category Recommendation Pairs
-- Combinations 조합 찾고 where로 filtering

WITH PP_SUMMARY AS (SELECT P1.USER_ID, I1.CATEGORY AS CATEGORY1, I2.CATEGORY AS CATEGORY2
FROM PRODUCTPURCHASES P1
JOIN PRODUCTPURCHASES P2 ON P1.USER_ID = P2.USER_ID
JOIN PRODUCTINFO I1 ON P1.PRODUCT_ID = I1.PRODUCT_ID
JOIN PRODUCTINFO I2 ON P2.PRODUCT_ID = I2.PRODUCT_ID
WHERE I1.CATEGORY < I2.CATEGORY
)

SELECT CATEGORY1, CATEGORY2, COUNT(DISTINCT USER_ID) AS CUSTOMER_COUNT
FROM PP_SUMMARY
GROUP BY CATEGORY1, CATEGORY2
HAVING CUSTOMER_COUNT >= 3
ORDER BY CUSTOMER_COUNT DESC, CATEGORY1, CATEGORY2