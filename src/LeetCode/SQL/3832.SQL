-- 3832. Find Users with Persistent Behavior Patterns

WITH STATUS_GROUP AS (SELECT USER_ID, ACTION_DATE, ACTION,
ROW_NUMBER() OVER (PARTITION BY USER_ID ORDER BY ACTION_DATE) -
ROW_NUMBER() OVER (PARTITION BY USER_ID, ACTION ORDER BY ACTION_DATE) AS ACTION_ID
FROM ACTIVITY),

STREAK_LIST AS (
    SELECT USER_ID, ACTION, COUNT(*) AS STREAK_LENGTH,
    MIN(ACTION_DATE) AS START_DATE, MAX(ACTION_DATE) AS END_DATE
    FROM STATUS_GROUP
    GROUP BY USER_ID, ACTION, ACTION_ID
    HAVING COUNT(*) >= 5
),

FINAL_RANK AS (
    SELECT *, RANK() OVER(PARTITION BY USER_ID ORDER BY STREAK_LENGTH DESC) AS RNK
    FROM STREAK_LIST
)

SELECT USER_ID, ACTION, STREAK_LENGTH, START_DATE, END_DATE
FROM FINAL_RANK
WHERE RNK = 1
ORDER BY STREAK_LENGTH DESC, USER_ID