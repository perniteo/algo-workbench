-- 3673. Find Zombie Sessions

WITH EVENTS_SUMMARY AS (
    SELECT SESSION_ID, USER_ID, TIMESTAMPDIFF(MINUTE, MIN(EVENT_TIMESTAMP), MAX(EVENT_TIMESTAMP)) AS DURATION,
    SUM(CASE WHEN EVENT_TYPE = 'scroll' THEN 1 ELSE 0 END) AS SCROLL_COUNT,
    SUM(CASE WHEN EVENT_TYPE = 'click' THEN 1 ELSE 0 END) AS CLICK_COUNT,
    SUM(CASE WHEN EVENT_TYPE = 'purchase' THEN 1 ELSE 0 END) AS PURCHASE_COUNT
    FROM APP_EVENTS GROUP BY SESSION_ID
    )

SELECT SESSION_ID, USER_ID, DURATION AS SESSION_DURATION_MINUTES, SCROLL_COUNT
FROM EVENTS_SUMMARY
WHERE CLICK_COUNT / SCROLL_COUNT < 0.2
AND DURATION > 30
AND PURCHASE_COUNT = 0
AND SCROLL_COUNT >= 5
ORDER BY SCROLL_COUNT DESC, SESSION_ID