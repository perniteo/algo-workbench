-- 3716. Find Churn Risk Customers

WITH USER_SUMMARY AS(
    SELECT USER_ID,
    DATEDIFF(MAX(EVENT_DATE), MIN(EVENT_DATE)) AS DAYS_AS_SUBSCRIBER,
    MAX(MONTHLY_AMOUNT) AS MAX_HISTORICAL_AMOUNT,
    MAX(EVENT_DATE) AS LAST_DATE,
    SUM(CASE WHEN EVENT_TYPE = 'downgrade' THEN 1 ELSE 0 END) AS DOWN_COUNT
    FROM SUBSCRIPTION_EVENTS
    GROUP BY USER_ID
),
RANKED_EVENT AS (
    SELECT *, ROW_NUMBER() OVER(PARTITION BY USER_ID ORDER BY EVENT_DATE DESC, EVENT_ID DESC) AS RN
    FROM SUBSCRIPTION_EVENTS
)

SELECT S.USER_ID, E.PLAN_NAME AS CURRENT_PLAN, E.MONTHLY_AMOUNT AS CURRENT_MONTHLY_AMOUNT, S.MAX_HISTORICAL_AMOUNT, S.DAYS_AS_SUBSCRIBER
FROM USER_SUMMARY S
JOIN RANKED_EVENT E
ON S.USER_ID = E.USER_ID AND S.LAST_DATE = E.EVENT_DATE
WHERE E.RN = 1
AND E.EVENT_TYPE != 'CANCEL'
AND DOWN_COUNT >= 1
AND DAYS_AS_SUBSCRIBER >= 60
AND E.MONTHLY_AMOUNT < (S.MAX_HISTORICAL_AMOUNT * 0.5)
ORDER BY S.DAYS_AS_SUBSCRIBER DESC, S.USER_ID