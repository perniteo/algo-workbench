-- 3764. Most Common Course Pairs

WITH SELECT_USER AS (SELECT USER_ID FROM COURSE_COMPLETIONS GROUP BY USER_ID HAVING COUNT(*) >= 5 AND AVG(COURSE_RATING) >= 4),

NEXT_COURSE AS (
    SELECT *, LEAD(COURSE_NAME) OVER (PARTITION BY USER_ID ORDER BY COMPLETION_DATE) AS NEXT
FROM COURSE_COMPLETIONS
WHERE USER_ID IN (SELECT USER_ID FROM SELECT_USER)
)

SELECT COURSE_NAME AS FIRST_COURSE, NEXT AS SECOND_COURSE, COUNT(*) AS TRANSITION_COUNT
FROM NEXT_COURSE
WHERE NEXT IS NOT NULL
GROUP BY FIRST_COURSE, SECOND_COURSE
ORDER BY TRANSITION_COUNT DESC, FIRST_COURSE, SECOND_COURSE