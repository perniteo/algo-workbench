-- 3642. Find Books with Polarized Opinions

    WITH SESSION_SUMMARY AS (
        SELECT BOOK_ID, COUNT(SESSION_ID) AS READING_COUNT, MAX(SESSION_RATING) - MIN(SESSION_RATING) AS SPREAD,
        SUM(CASE WHEN SESSION_RATING <= 2 THEN 1 ELSE 0 END) AS LOW_COUNT,
        SUM(CASE WHEN SESSION_RATING >= 4 THEN 1 ELSE 0 END) AS HIGH_COUNT,
        SUM(CASE WHEN SESSION_RATING <= 2 OR SESSION_RATING >= 4 THEN 1 ELSE 0 END) AS P_SCORE
        FROM READING_SESSIONS
        GROUP BY BOOK_ID)

    SELECT S.BOOK_ID, B.TITLE, B.AUTHOR, B.GENRE, B.PAGES, S.SPREAD AS RATING_SPREAD, ROUND(P_SCORE / READING_COUNT, 2) AS POLARIZATION_SCORE
    FROM SESSION_SUMMARY S
    JOIN BOOKS B ON S.BOOK_ID = B.BOOK_ID
    WHERE READING_COUNT >= 5
    AND P_SCORE / READING_COUNT >= 0.6
    AND LOW_COUNT > 0
    AND HIGH_COUNT > 0
    ORDER BY POLARIZATION_SCORE DESC, B.TITLE DESC