WITH PRODUCT_RANKING AS (
    SELECT *, RANK() OVER(PARTITION BY STORE_ID ORDER BY PRICE DESC) AS EXPENSIVE_RANK,
    RANK() OVER(PARTITION BY STORE_ID ORDER BY PRICE) AS CHEAPEST_RANK
    FROM INVENTORY
),

INVENTORY_SUMMARY AS (
    SELECT STORE_ID,
    MAX(CASE WHEN EXPENSIVE_RANK = 1 THEN PRODUCT_NAME END) AS MOST_EXP_PRODUCT,
    MAX(CASE WHEN EXPENSIVE_RANK = 1 THEN QUANTITY END) AS EXP_QUANTITY,
    MAX(CASE WHEN CHEAPEST_RANK = 1 THEN PRODUCT_NAME END) AS CHEAPEST_PRODUCT,
    MAX(CASE WHEN CHEAPEST_RANK = 1 THEN QUANTITY END) AS CHEAP_QUANTITY,
    COUNT(*) AS COUNT
    FROM PRODUCT_RANKING
    GROUP BY STORE_ID
),

LAST_SUMMARY AS (
    SELECT STORE_ID, MOST_EXP_PRODUCT, CHEAPEST_PRODUCT, ROUND(CHEAP_QUANTITY / EXP_QUANTITY, 2) AS IMBALANCE_RATIO
    FROM INVENTORY_SUMMARY
    WHERE EXP_QUANTITY < CHEAP_QUANTITY
    AND COUNT >= 3
    )

SELECT L.STORE_ID, S.STORE_NAME, S.LOCATION, L.MOST_EXP_PRODUCT, L.CHEAPEST_PRODUCT, L.IMBALANCE_RATIO
FROM LAST_SUMMARY L
JOIN STORES S ON L.STORE_ID = S.STORE_ID
ORDER BY L.IMBALANCE_RATIO DESC, S.STORE_NAME