-- 3601. Find Drivers with Improved Fuel Efficiency

WITH HALF_TRIPS AS (
    SELECT *, CASE WHEN MONTH(TRIP_DATE) <= 6 THEN 'FIRST' ELSE 'SECOND' END AS HALF FROM TRIPS
),
HALF_SUMMARY AS (
    SELECT DRIVER_ID, AVG(DISTANCE_KM / FUEL_CONSUMED) AS HALF_AVG, HALF FROM HALF_TRIPS
    GROUP BY DRIVER_ID, HALF
),

LAST_SUMMARY AS (SELECT DRIVER_ID,
MAX(CASE WHEN HALF = 'FIRST' THEN HALF_AVG END) AS FIRST_HALF_AVG,
MAX(CASE WHEN HALF = 'SECOND' THEN HALF_AVG END) AS SECOND_HALF_AVG

FROM HALF_SUMMARY
GROUP BY DRIVER_ID
HAVING FIRST_HALF_AVG IS NOT NULL
AND SECOND_HALF_AVG IS NOT NULL
AND SECOND_HALF_AVG - FIRST_HALF_AVG > 0)

SELECT S.DRIVER_ID, D.DRIVER_NAME,
ROUND(S.FIRST_HALF_AVG, 2) AS FIRST_HALF_AVG,
ROUND(S.SECOND_HALF_AVG, 2) AS SECOND_HALF_AVG,
ROUND(S.SECOND_HALF_AVG - S.FIRST_HALF_AVG, 2) AS EFFICIENCY_IMPROVEMENT
FROM LAST_SUMMARY S
JOIN DRIVERS D ON S.DRIVER_ID = D.DRIVER_ID
ORDER BY EFFICIENCY_IMPROVEMENT DESC, D.DRIVER_NAME