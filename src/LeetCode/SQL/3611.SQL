-- 3611. Find Overbooked Employees

WITH DATE_GROUP AS (
    SELECT MEETING_ID, EMPLOYEE_ID,
    DATE_SUB(MEETING_DATE, INTERVAL WEEKDAY(MEETING_DATE) DAY) AS WEEK_MEETING,
    MEETING_TYPE, DURATION_HOURS
    FROM MEETINGS
),
WEEK_SUMMARY AS (
    SELECT EMPLOYEE_ID, SUM(DURATION_HOURS) AS TOTAL_HOURS FROM DATE_GROUP
    GROUP BY EMPLOYEE_ID, WEEK_MEETING
)

SELECT S.EMPLOYEE_ID, E.EMPLOYEE_NAME, E.DEPARTMENT, COUNT(*) AS MEETING_HEAVY_WEEKS
FROM WEEK_SUMMARY S
JOIN EMPLOYEES E ON S.EMPLOYEE_ID = E.EMPLOYEE_ID
WHERE S.WEEK_MEETING >= 20
GROUP BY S.EMPLOYEE_ID
HAVING COUNT(*) >= 2
ORDER BY MEETING_HEAVY_WEEKS DESC, EMPLOYEE_NAME